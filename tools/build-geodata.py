#!/usr/bin/env python3
"""Builds data/geodata.js from Natural Earth GeoJSON (public domain).
Usage: python3 tools/build-geodata.py <dir-with-ne_10m_*.json> 
Inputs: ne_10m_lakes, ne_10m_rivers_lake_centerlines, ne_10m_geography_regions_polys,
        ne_10m_geography_marine_polys, ne_10m_populated_places_simple (saved as .json)."""
import json, math, sys, os
src = sys.argv[1]
out = os.path.join(os.path.dirname(__file__), "..", "data", "geodata.js")
load = lambda n: json.load(open(os.path.join(src, n + ".json")))["features"]
r2 = lambda x: round(x, 2)
KM = 111.0

def rings(g):
    if g["type"] == "Polygon": return [g["coordinates"][0]]
    if g["type"] == "MultiPolygon": return [p[0] for p in g["coordinates"]]
    return []

def area_info(g):
    best = None
    for ring in rings(g):
        lons = [c[0] for c in ring]; lats = [c[1] for c in ring]
        a = (max(lons) - min(lons)) * (max(lats) - min(lats))
        if best is None or a > best[0]: best = (a, ring, min(lons), max(lons), min(lats), max(lats))
    if not best: return None
    _, ring, x0, x1, y0, y1 = best
    lat = (y0 + y1) / 2; lon = (x0 + x1) / 2
    ext = max((x1 - x0) * math.cos(math.radians(lat)), (y1 - y0)) * KM  # km across
    return lat, lon, ext

def line_pts(g, step_km):
    lines = g["coordinates"] if g["type"] == "MultiLineString" else [g["coordinates"]]
    pts = []
    for ln in lines:
        last = None
        for lon, lat in ln:
            if last is None or math.hypot((lon - last[0]) * math.cos(math.radians(lat)), lat - last[1]) * KM >= step_km:
                pts.append((lat, lon)); last = (lon, lat)
    return pts

d = {"lakes": [], "rivers": [], "areas": [], "cities": []}

for f in load("ne_10m_lakes"):
    p = f["properties"]; n = p.get("name_en") or p.get("name")
    if not n or not f["geometry"]: continue
    ai = area_info(f["geometry"])
    if not ai or ai[2] < 6: continue
    d["lakes"].append([n, r2(ai[0]), r2(ai[1]), round(ai[2]), p.get("admin") or ""])

seen = {}
for f in load("ne_10m_rivers_lake_centerlines"):
    p = f["properties"]; n = p.get("name_en") or p.get("name")
    if not n or not f["geometry"] or p.get("scalerank", 99) > 9: continue
    pts = line_pts(f["geometry"], 25)
    if len(pts) < 2: continue
    seen.setdefault(n, []).extend(pts)
for n, pts in seen.items():
    flat = []
    for la, lo in pts: flat += [r2(la), r2(lo)]
    d["rivers"].append([n, flat])

KEEP = {"Range/mtn": "range", "Desert": "desert", "Plateau": "plateau", "Island group": "island", "Archipelago": "island",
        "Island": "island", "Peninsula": "plateau", "Depression": "plateau", "Basin": "plateau", "Lowland/plain": "plateau",
        "Isthmus": "plateau", "Delta": "river", "Coast": "sea", "Valley": "plateau"}
for f in load("ne_10m_geography_regions_polys"):
    p = f["properties"]; cls = p.get("FEATURECLA"); n = p.get("NAME_EN") or p.get("NAME")
    t = KEEP.get(cls)
    if not t or not n or not f["geometry"]: continue
    ai = area_info(f["geometry"])
    if not ai or ai[2] < 25: continue
    d["areas"].append([n, t, r2(ai[0]), r2(ai[1]), round(ai[2])])
for f in load("ne_10m_geography_marine_polys"):
    p = f["properties"]; n = p.get("name") or p.get("NAME")
    if not n or not f["geometry"] or "Ocean" in n: continue
    ai = area_info(f["geometry"])
    if not ai or ai[2] < 40: continue
    d["areas"].append([n, "sea", r2(ai[0]), r2(ai[1]), round(ai[2])])

for f in load("ne_10m_populated_places_simple"):
    p = f["properties"]
    if (p.get("pop_max") or 0) < 300000: continue
    d["cities"].append([p["name"], p.get("adm0name") or "", r2(p["latitude"]), r2(p["longitude"]), int(p["pop_max"])])

with open(out, "w") as fh:
    fh.write("// GENERATED by tools/build-geodata.py from Natural Earth (public domain). Do not edit by hand.\n")
    fh.write("window.GEODATA = " + json.dumps(d, separators=(",", ":"), ensure_ascii=False) + ";\n")
print({k: len(v) for k, v in d.items()}, os.path.getsize(out) // 1024, "KB")
