#!/usr/bin/env python3
"""Builds data/land.js (simplified coastlines) from Natural Earth ne_10m_land (public domain).
Usage: python3 tools/build-land.py <ne_10m_land.json> [tolerance_deg] [min_area_deg2]
Output: window.LAND = [[lon0,lat0,lon1,lat1, ring, ring, ...], ...] with all numbers in 1/100 degree integers;
rings are flat [lon,lat,lon,lat,...] (first ring = outline, others = holes)."""
import json, math, os, sys
src = sys.argv[1]; tol = float(sys.argv[2]) if len(sys.argv) > 2 else 0.012; min_area = float(sys.argv[3]) if len(sys.argv) > 3 else 0.004
out = os.path.join(os.path.dirname(__file__), "..", "data", "land.js")

def dp(pts, eps):  # Douglas-Peucker, iterative
    n = len(pts)
    if n < 3: return pts
    keep = [False] * n; keep[0] = keep[-1] = True; stack = [(0, n - 1)]
    while stack:
        a, b = stack.pop(); ax, ay = pts[a]; bx, by = pts[b]; dx, dy = bx - ax, by - ay; L = dx * dx + dy * dy
        best, bi = -1, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            if L == 0: d = math.hypot(px - ax, py - ay)
            else:
                t = max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / L)); d = math.hypot(px - ax - t * dx, py - ay - t * dy)
            if d > best: best, bi = d, i
        if best > eps: keep[bi] = True; stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]

def area(r):
    return abs(sum(r[i][0] * r[i + 1][1] - r[i + 1][0] * r[i][1] for i in range(len(r) - 1))) / 2

res = []; npts = 0
for f in json.load(open(src))["features"]:
    g = f["geometry"]; polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
    for poly in polys:
        outer = poly[0]
        lons = [c[0] for c in outer]; lats = [c[1] for c in outer]
        if max(lats) < -60 or area(outer) < min_area: continue
        rings = []
        for k, r in enumerate(poly):
            if k and area(r) < min_area: continue
            s = dp([(c[0], c[1]) for c in r], tol)
            if len(s) < 4: continue
            flat = []
            for x, y in s: flat += [round(x * 100), round(y * 100)]
            rings.append(flat); npts += len(s)
        if rings: res.append([round(min(lons) * 100), round(min(lats) * 100), round(max(lons) * 100), round(max(lats) * 100)] + rings)
with open(out, "w") as fh:
    fh.write("// GENERATED by tools/build-land.py from Natural Earth ne_10m_land (public domain). Do not hand-edit.\n")
    fh.write("// [lon0,lat0,lon1,lat1, outline, hole...] in 1/100 degree; rings are flat lon,lat pairs.\n")
    fh.write("window.LAND = " + json.dumps(res, separators=(",", ":")) + ";\n")
print(len(res), "polygons", npts, "points", os.path.getsize(out) // 1024, "KB")
